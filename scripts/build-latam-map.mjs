/**
 * One-shot: Natural Earth 50m Admin 0 → LatAm SVG paths (public domain).
 * Made with Natural Earth. https://www.naturalearthdata.com/
 *
 * Usage: node scripts/build-latam-map.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const ISO = [
  "MX",
  "GT",
  "HN",
  "SV",
  "NI",
  "CR",
  "PA",
  "DO",
  "CO",
  "VE",
  "EC",
  "PE",
  "BO",
  "PY",
  "BR",
  "UY",
  "AR",
  "CL",
];

const WIDTH = 720;
const HEIGHT = 860;
const PAD = 12;

const geo = JSON.parse(
  fs.readFileSync(
    path.join(__dirname, "ne_50m_admin_0_countries.geojson"),
    "utf8",
  ),
);

const byIso = new Map();
for (const feature of geo.features) {
  const iso = feature.properties?.ISO_A2_EH || feature.properties?.ISO_A2;
  if (!ISO.includes(iso)) continue;
  // Prefer mainland-sized features; merge if duplicate ISO appears
  if (!byIso.has(iso)) byIso.set(iso, feature);
}

const missing = ISO.filter((iso) => !byIso.has(iso));
if (missing.length) {
  console.error("Missing ISO:", missing.join(", "));
  process.exit(1);
}

/** Equirectangular lon/lat → [x,y] before fit */
function project(lon, lat) {
  return [lon, -lat];
}

function ringBounds(ring, bounds) {
  for (const [lon, lat] of ring) {
    const [x, y] = project(lon, lat);
    if (x < bounds.minX) bounds.minX = x;
    if (x > bounds.maxX) bounds.maxX = x;
    if (y < bounds.minY) bounds.minY = y;
    if (y > bounds.maxY) bounds.maxY = y;
  }
}

function geometryBounds(geometry, bounds) {
  if (geometry.type === "Polygon") {
    for (const ring of geometry.coordinates) ringBounds(ring, bounds);
  } else if (geometry.type === "MultiPolygon") {
    for (const poly of geometry.coordinates) {
      for (const ring of poly) ringBounds(ring, bounds);
    }
  }
}

const bounds = {
  minX: Infinity,
  minY: Infinity,
  maxX: -Infinity,
  maxY: -Infinity,
};
for (const iso of ISO) {
  geometryBounds(byIso.get(iso).geometry, bounds);
}

const bw = bounds.maxX - bounds.minX;
const bh = bounds.maxY - bounds.minY;
const scale = Math.min(
  (WIDTH - PAD * 2) / bw,
  (HEIGHT - PAD * 2) / bh,
);
const ox = PAD + ((WIDTH - PAD * 2) - bw * scale) / 2 - bounds.minX * scale;
const oy = PAD + ((HEIGHT - PAD * 2) - bh * scale) / 2 - bounds.minY * scale;

function toSvg([lon, lat]) {
  const [x, y] = project(lon, lat);
  return [
    Math.round((x * scale + ox) * 100) / 100,
    Math.round((y * scale + oy) * 100) / 100,
  ];
}

function ringToPath(ring, close) {
  if (!ring.length) return "";
  const parts = [];
  for (let i = 0; i < ring.length; i++) {
    const [x, y] = toSvg(ring[i]);
    parts.push(i === 0 ? `M${x} ${y}` : `L${x} ${y}`);
  }
  if (close) parts.push("Z");
  return parts.join(" ");
}

function geometryToPath(geometry) {
  const chunks = [];
  if (geometry.type === "Polygon") {
    for (const ring of geometry.coordinates) {
      chunks.push(ringToPath(ring, true));
    }
  } else if (geometry.type === "MultiPolygon") {
    for (const poly of geometry.coordinates) {
      for (const ring of poly) {
        chunks.push(ringToPath(ring, true));
      }
    }
  }
  return chunks.join(" ");
}

const paths = {};
for (const iso of ISO) {
  paths[iso] = geometryToPath(byIso.get(iso).geometry);
}

const svgPaths = ISO.map(
  (iso) =>
    `  <path data-iso="${iso}" d="${paths[iso]}" />`,
).join("\n");

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Made with Natural Earth (public domain). https://www.naturalearthdata.com/ -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" role="img" aria-label="Latin America">
${svgPaths}
</svg>
`;

fs.writeFileSync(path.join(root, "public", "brand", "maps", "latam.svg"), svg);

const ts = `import type { CountryIso } from "@/lib/gafiLatamContent";

/**
 * Geographic LatAm country paths projected from Natural Earth 50m Admin 0
 * (public domain). Made with Natural Earth — https://www.naturalearthdata.com/
 * Regenerated by: node scripts/build-latam-map.mjs
 */
export const LATAM_MAP_PATHS: Record<CountryIso, string> = {
${ISO.map((iso) => `  ${iso}: ${JSON.stringify(paths[iso])},`).join("\n")}
};

export const LATAM_MAP_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";
`;

fs.writeFileSync(path.join(root, "src", "lib", "latAmMapPaths.ts"), ts);

console.log(
  `Wrote ${ISO.length} countries → public/brand/maps/latam.svg + src/lib/latAmMapPaths.ts`,
);
